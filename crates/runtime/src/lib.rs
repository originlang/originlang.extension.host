//! Execution backend abstraction.
//!
//! The host orchestrates lifecycle, authorization and storage; it never assumes
//! how extension code runs. A backend implements [`Runtime`] and produces
//! instances through a [`RuntimeProvider`]. Two backends use this contract: an
//! in-process QuickJS worker and an out-of-process sandbox; the host cannot tell
//! them apart.
//!
//! The contract is intentionally narrow: registration, invocation, event
//! delivery, shutdown. Everything else an extension can do must travel through
//! [`HostBridge`], which is where capabilities are enforced. That property is
//! what makes out-of-process isolation cheap: the process boundary carries
//! nothing but Host API requests, so the authorization decision does not move —
//! only the code under suspicion does.
//!
//! [`CallChain`] travels with every invocation because it is the only state that
//! a backend cannot reconstruct on its own: a cross-extension call nests across
//! threads once a child process is involved, and the host needs the stack that
//! led here to reject a cycle instead of deadlocking on it.

use originlang_ext_protocol::RpcError;
use serde::{Deserialize, Serialize};
use serde_json::Value;
use std::path::Path;
use std::sync::Arc;
use std::time::Duration;

/// Metadata an extension reports once it is initialized.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ExtensionInfo {
    /// Identity declared by the extension; must match the installed manifest.
    pub id: String,
    /// Version declared by the extension.
    pub version: String,
    /// Callable methods.
    #[serde(default)]
    pub methods: Vec<String>,
    /// Capabilities declared by the extension.
    #[serde(default)]
    pub capabilities: Vec<String>,
}

/// Extension ids already on the caller's stack, outermost first.
///
/// The last element is the instance being invoked. Backends must pass the slice
/// back unchanged on every [`HostBridge`] call: the host keeps one authoritative
/// stack this way even after the call has crossed a process and a thread
/// boundary, which is the difference between rejecting a `a -> b -> a` cycle and
/// deadlocking on it.
pub type CallChain = [String];

/// Host services exposed to a running extension.
///
/// Implemented by the host. Every method is a potential privilege boundary, so
/// implementations must authorize before acting and must never trust arguments
/// that identify an extension.
pub trait HostBridge: Send + Sync {
    /// Dispatches one Host API call made by the extension at the top of `chain`.
    fn call(
        &self,
        method: &str,
        params: Option<Value>,
        chain: &CallChain,
    ) -> Result<Value, RpcError>;

    /// Records a log line attributed to this extension.
    fn log(&self, level: &str, message: &str);
}

/// Resource ceilings for one extension instance.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct RuntimeLimits {
    /// Heap ceiling in bytes.
    pub memory_bytes: usize,
    /// Stack ceiling in bytes.
    pub stack_bytes: usize,
    /// Wall-clock ceiling for a single invocation.
    pub timeout: Duration,
}

impl Default for RuntimeLimits {
    fn default() -> Self {
        Self {
            memory_bytes: 64 * 1024 * 1024,
            stack_bytes: 512 * 1024,
            timeout: Duration::from_secs(10),
        }
    }
}

/// Everything a provider needs to start one extension instance.
pub struct RuntimeSpec<'a> {
    /// Installed identity, used for diagnostics and log attribution.
    pub id: &'a str,
    /// Backend the manifest asked for.
    ///
    /// A concrete provider ignores this — it already is the backend. It exists
    /// so that a router can dispatch, which is the only consumer that needs to
    /// know the answer before choosing an implementation.
    pub backend: &'a str,
    /// Absolute path of the entry module, already validated to be inside the
    /// extension directory.
    pub entry: &'a Path,
    /// Resource ceilings.
    pub limits: RuntimeLimits,
    /// Host services for this instance.
    pub bridge: Arc<dyn HostBridge>,
}

/// An event delivered to an extension.
///
/// The shape is fixed here rather than in each backend so that `onEvent` sees
/// the same object regardless of runtime.
#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Event {
    /// Topic name, matching what publishers and subscribers agreed on.
    pub topic: String,
    /// Event body; opaque to the host.
    pub payload: Value,
    /// Publisher identity, absent for host-generated events.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub from: Option<String>,
}

impl Event {
    /// Event generated by the host (timer, lifecycle).
    pub fn host(topic: impl Into<String>, payload: Value) -> Self {
        Self {
            topic: topic.into(),
            payload,
            from: None,
        }
    }

    /// Event published by another extension.
    pub fn from_extension(
        topic: impl Into<String>,
        payload: Value,
        from: impl Into<String>,
    ) -> Self {
        Self {
            topic: topic.into(),
            payload,
            from: Some(from.into()),
        }
    }
}

/// A live extension instance.
///
/// Calls are serialized by the owner; implementations may assume `&mut self`
/// implies exclusive access and need not be internally synchronized.
pub trait Runtime: Send {
    /// Initializes the extension and returns its metadata.
    fn register(&mut self) -> Result<ExtensionInfo, RpcError>;

    /// Invokes one method with the caller's stack.
    fn call(
        &mut self,
        method: &str,
        params: Option<Value>,
        chain: &CallChain,
    ) -> Result<Value, RpcError>;

    /// Delivers an event. Failures are reported but must not stop the host:
    /// an extension that throws on one event should still answer calls.
    fn emit(&mut self, event: Event, chain: &CallChain) -> Result<(), RpcError>;

    /// True while the backend is still able to serve calls.
    fn is_running(&self) -> bool;

    /// Runs the extension's cleanup hook and stops the backend.
    fn shutdown(&mut self) -> Result<(), RpcError>;
}

/// Factory for one backend.
///
/// `Send + Sync` because a host may load extensions from several threads.
pub trait RuntimeProvider: Send + Sync {
    /// Backend identifier, surfaced in diagnostics (`"quickjs"`).
    fn kind(&self) -> &'static str;

    /// Backends reachable through this provider.
    ///
    /// A concrete backend is a single value. A router lists everything it was
    /// built with, which is what makes `host.info` able to report the whole set
    /// without the host knowing about routers.
    fn available(&self) -> Vec<&'static str> {
        vec![self.kind()]
    }

    /// Starts one instance.
    fn start(&self, spec: RuntimeSpec<'_>) -> Result<Box<dyn Runtime>, RpcError>;
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn limits_default_is_the_documented_ceiling() {
        let limits = RuntimeLimits::default();
        assert_eq!(limits.memory_bytes, 64 * 1024 * 1024);
        assert_eq!(limits.stack_bytes, 512 * 1024);
        assert_eq!(limits.timeout, Duration::from_secs(10));
    }
}
